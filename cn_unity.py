def _prune_empty(root, rel_dir):
    """从里往外删空文件夹，有东西的不动"""
    d = os.path.join(root, rel_dir)
    for dirpath, dirnames, filenames in sorted(os.walk(d, topdown=False), key=lambda x: -len(x[0])):
        try:
            if not os.listdir(dirpath):
                os.rmdir(dirpath)
        except OSError:
            pass


_XUNITY_DIRS = ("BepInEx/plugins/XUnity.AutoTranslator/", "BepInEx/plugins/XUnity.ResourceRedirector/")


def _is_xunity_file(rel):
    """翻译插件自己的文件（其余的是 BepInEx 加载器）"""
    return (rel.startswith(_XUNITY_DIRS) or os.path.basename(rel).startswith("XUnity.")
            or rel == "BepInEx/config/AutoTranslatorConfig.ini")


def _foreign_mods(root, created):
    """BepInEx 里不是这个工具装的 mod 文件（plugins / patchers 里多出来的）"""
    mine = set(created)
    found = []
    for sub in ("BepInEx/plugins", "BepInEx/patchers"):
        for dirpath, dirnames, filenames in os.walk(os.path.join(root, sub)):
            for fn in filenames:
                rel = os.path.relpath(os.path.join(dirpath, fn), root).replace("\\", "/")
                if rel not in mine and not rel.startswith(_XUNITY_DIRS):
                    found.append(rel)
    return found


def remove(root, log):
    """只删这个工具装进去的文件；游戏里原来就有、或者你后来自己加的 mod 都不动。
    返回 None：不是这个工具装的；"removed"：拿掉了（BepInEx 是工具装的话也一起拿掉，恢复原版）；
    "kept_loader"：BepInEx 里有你别的 mod，只拿掉翻译插件，加载器留着；"partial"：有文件删不掉（游戏多半还开着）"""
    man_path = core._data_path(root, "unity_manifest")
    man = core.read_json(man_path, None)
    if not man:
        return None
    created = list(man.get("created", []))
    by_tool = bool(man.get("bepinex_by_tool"))
    foreign = _foreign_mods(root, created) if by_tool else []
    full = by_tool and not foreign
    targets = created if full else [rel for rel in created if _is_xunity_file(rel)]
    kept = [rel for rel in created if rel not in set(targets)]
    remaining = []
    for rel in targets:
        p = os.path.join(root, rel)
        try:
            if os.path.isfile(p):
                os.remove(p)
        except OSError as e:
            remaining.append(rel)
            if len(remaining) <= 3:
                log("  删不掉 %s（%s）" % (rel, e))
    if full and not remaining:
        for rel in _GENERATED:
            p = os.path.join(root, rel)
            if os.path.isdir(p):
                shutil.rmtree(p, ignore_errors=True)
            elif os.path.isfile(p):
                try:
                    os.remove(p)
                except OSError:
                    pass
    for d in ("BepInEx", "dotnet"):
        if os.path.isdir(os.path.join(root, d)):
            _prune_empty(root, d)
    if remaining or kept:
        # 清单留着：删不掉的下次再删；留下的加载器以后你删了别的 mod，再点「还原」能一起清掉
        man["created"] = remaining + kept
        core.write_json(man_path, man, indent=1)
    else:
        try:
            os.remove(man_path)
        except OSError:
            pass
    if remaining:
        return "partial"
    if kept and foreign:
        log("  BepInEx 里有别的 mod（例如 %s），插件加载器留着没删，不然那些 mod 会失效"
            % "、".join(foreign[:3]))
        return "kept_loader"
    return "removed"


def translated_count(root):
    p = translation_file(root)
    n = 0
    try:
        with open(p, "r", encoding="utf-8-sig", errors="replace") as f:
            for line in f:
                if "=" in line and not line.startswith("//"):
                    n += 1
    except OSError:
        pass
    return n


