# ============================================================== 本地翻译服务（插件把文字发到这里）

UNITY_TOKEN_RE = re.compile(r"<[^<>\n]{1,80}>|\{\{[^{}]*\}\}|\{\d+(?:,-?\d+)?(?::[^{}]*)?\}")

UNITY_PROMPT = """你是资深游戏本地化译者。把用户发来的这段游戏文本翻译成简体中文。
只输出译文本身：不要加引号、解释、注释或任何多余内容。
<...> 形式的富文本标签、{{A}} 和 {0} 这类占位符必须原样保留，不要翻译、不要删。
保留原文的换行。人名、地名用常见音译。语气口语化，保留原文的情绪和粗口程度；界面按钮类短词用中文游戏里的常见说法。
%s"""

_SAME_RULE = {
    # 原文是日语 / 繁体时，不能叫模型「是中文就原样输出」，不然只有汉字的日文、繁体字都会原样回来
    "ja": "原文是日语：只有汉字的日文词句也要翻成简体中文（如「開始」→「开始」）。只是数字/符号/代码的原样输出。",
    "zh-TW": "原文是繁体中文：转成简体中文，并换成中国大陆的常用说法。只是数字/符号/代码的原样输出。",
}
_DEFAULT_SAME_RULE = "如果原文已经是简体中文、或者只是数字/符号/代码，原样输出。"

_HANGUL_RE = re.compile(r"[ᄀ-ᇿ㄰-㆏가-힯]")
_HAN_KANA_RE = re.compile(r"[぀-ヿ㐀-䶿一-鿿豈-﫿]")


def need_translate(text, src_lang):
    """Ren'Py 那套判断只认拉丁/西里尔字母和假名；Unity 按你选的原文语言再补上韩文、纯汉字"""
    if core.need_translate(text):
        return True
    t = text.strip()
    if not t or len(t) > 5000:
        return False
    bare = UNITY_TOKEN_RE.sub("", t)
    if src_lang == "ko":
        return bool(_HANGUL_RE.search(bare))
    if src_lang in ("ja", "zh-TW"):
        return bool(_HAN_KANA_RE.search(bare))
    return False


class _Server(ThreadingMixIn, HTTPServer):
    daemon_threads = True
    allow_reuse_address = True


class TranslateService(object):
    def __init__(self, cfg, log):
        self.cfg = cfg  # 和界面共用同一个 dict，改设置立刻生效
        self.log = log
        self.usage = core.Usage()
        self.lock = threading.Lock()
        self.file_lock = threading.Lock()  # 存盘、删除都排队写，旧快照不会盖掉新内容
        self.broken = None
        try:
            self.cache = core.read_json(CACHE_PATH, {}) or {}
            self.meta = core.read_json(META_PATH, {}) or {}
        except core.DataFileError as e:
            # 缓存文件坏了：不能当空的用，不然自动保存会把它盖掉、翻过的又要重新花钱
            self.cache, self.meta = {}, {}
            self.broken = str(e)
            log("Unity 翻译缓存读不了，Unity 边玩边翻先停用：%s" % e)
        self.dirty = 0
        self.count = 0
        self.failed = 0
        self.current_game = ""
        self.stop = threading.Event()
        self.httpd = None
        self._logged_since = (0, 0, 0)
        self._auth_warned = False
        self._save_warned = False
        self._pending = {}  # 正在翻的句子 -> Event，同一句同时来两次只调一次 API
        self._busy = 0

    # ---------------------------------------------------------- 服务
    def start(self):
        svc = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def do_GET(self):
                u = urllib.parse.urlparse(self.path)
                if u.path.rstrip("/") != "/translate":
                    self.send_response(404)
                    self.end_headers()
                    return
                q = urllib.parse.parse_qs(u.query, keep_blank_values=True)
                text = (q.get("text") or [""])[0]
                try:
                    res = svc.translate(text)
                    code = 200
                except Exception as e:
                    res, code = str(e), 500
                body = res.encode("utf-8")
                self.send_response(code)
                self.send_header("Content-Type", "text/plain; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

        try:
            self.httpd = _Server(("127.0.0.1", PORT), H)
        except OSError:
            self.httpd = None
            return False
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()
        threading.Thread(target=self._autosave, daemon=True).start()
        return True

    def busy(self):
        return self._busy

    def shutdown(self, wait_seconds=0):
        """关之前先等已经发出去的请求回来（已经付了钱），再存盘"""
        end = time.time() + wait_seconds
        while self._busy and time.time() < end:
            time.sleep(0.2)
        self.stop.set()
        self.save()
        self.flush_usage()
        if self.httpd:
            try:
                self.httpd.shutdown()
                self.httpd.server_close()
            except Exception:
                pass

    def _autosave(self):
        while not self.stop.wait(10):
            self.save()

    def save(self):
        """返回 True = 硬盘上已经是最新的；False = 有新译文没存进去"""
        if self.broken:
            return True  # 缓存文件坏了的时候服务没在翻，内存里没有新东西
        with self.file_lock:
            with self.lock:
                if not self.dirty:
                    return True
                data = dict(self.cache)
                meta = dict(self.meta)
                n, self.dirty = self.dirty, 0
            try:
                core.write_json(CACHE_PATH, data, indent=1)
                core.write_json(META_PATH, meta, indent=1)
                self._save_warned = False
                return True
            except Exception as e:
                with self.lock:
                    self.dirty += n  # 下次再试（条数也保留，关工具时提示才准）
                if not self._save_warned:
                    self._save_warned = True
                    self.log("Unity 翻译缓存保存失败（%s），会自动重试；一直失败的话检查工具文件夹是不是只读" % e)
                return False

    def unsaved(self):
        """还没存进硬盘的新译文条数（大概）"""
        with self.lock:
            return self.dirty

    def delete_translations(self, root, model):
        """删某个模型翻的句子：直接在内存缓存里删再整份写盘。
        内存里的缓存比硬盘上的全（还没来得及自动保存的也在），所以不用重新读盘，不会丢东西"""
        if self.broken:
            raise RuntimeError(self.broken)
        with self.file_lock:
            p, lines = _game_entries(root)
            keep, gone = [], 0
            with self.lock:
                if self._pending:
                    # 有请求在路上：删完它回来又会把译文写回去。检查和删除在同一把锁里，中间插不进新请求
                    raise RuntimeError("游戏正在请求翻译（%d 句在路上），先关掉游戏再删" % len(self._pending))
                for line in lines:
                    k, v = _split_line(line) if not line.startswith("//") else (None, None)
                    if k is not None:
                        key = _unescape(k)
                        if model is None or self.meta.get(key, core.UNKNOWN_MODEL) == model:
                            gone += 1
                            self.cache.pop(key, None)
                            self.meta.pop(key, None)
                            continue
                    keep.append(line)
                data, meta = dict(self.cache), dict(self.meta)
                was_dirty, self.dirty = self.dirty, 0
            if not gone:
                with self.lock:
                    self.dirty += was_dirty
                return 0
            try:
                with open(p, "w", encoding="utf-8") as f:
                    f.write("\n".join(keep) + ("\n" if keep else ""))
                core.write_json(CACHE_PATH, data, indent=1)
                core.write_json(META_PATH, meta, indent=1)
            except Exception:
                with self.lock:
                    self.dirty += was_dirty + 1  # 内存里已经删了，自动保存会再写一次
                raise
            return gone

    def set_game(self, title):
        self.flush_usage()
        self.current_game = title

    def flush_usage(self):
        now = (self.usage.hit, self.usage.miss, self.usage.out)
        if now != self._logged_since:
            core.log_usage("[Unity] " + (self.current_game or "未知游戏"), self.cfg, self._logged_since, now)
            self._logged_since = now

    # ---------------------------------------------------------- 翻译一句
    def translate(self, text):
        if not text or not text.strip():
            return text
        if self.broken:
            raise RuntimeError("translation cache file is broken, see the tool window")
        while True:
            with self.lock:
                hit = self.cache.get(text)
                if hit is not None:
                    return hit
                ev = self._pending.get(text)
                if ev is None:
                    ev = self._pending[text] = threading.Event()
                    break
            ev.wait(120)  # 同一句别人正在翻，等它的结果
            with self.lock:
                hit = self.cache.get(text)
            if hit is not None:
                return hit
            raise RuntimeError("translation failed")
        try:
            with self.lock:
                self._busy += 1
            return self._translate_new(text)
        finally:
            with self.lock:
                self._busy -= 1
                self._pending.pop(text, None)
            ev.set()

    def _translate_new(self, text):
        cfg = dict(self.cfg)
        src_lang = cfg.get("unity_from_lang") or "en"
        if not need_translate(text, src_lang):
            return text
        if not cfg.get("api_key"):
            raise RuntimeError("tool has no API key")
        cfg["json_mode"] = False
        p = UNITY_PROMPT % _SAME_RULE.get(src_lang, _DEFAULT_SAME_RULE)
        gl = {k: v for k, v in (cfg.get("glossary") or {}).items() if k and v}
        if gl:
            p += "\n\n专有名词固定译法（必须遵守）：\n" + "\n".join("- %s → %s" % (k, v) for k, v in gl.items())
        if cfg.get("extra_prompt"):
            p += "\n\n额外要求：" + cfg["extra_prompt"]
        msgs = [{"role": "system", "content": p}, {"role": "user", "content": text}]
        want = core.Counter(UNITY_TOKEN_RE.findall(text))
        out = None
        for _ in range(2):
            try:
                r = core.call_with_retry(cfg, msgs, self.usage, self.stop, tries=3).strip()  # 关工具时不再重试
            except core.AuthError as e:
                if not self._auth_warned:
                    self._auth_warned = True
                    self.log("Unity 翻译：接口拒绝了请求（%s），检查 key / 余额 / 模型名。" % e)
                raise
            if len(r) >= 2 and r[0] in "\"“「'" and r[-1] in "\"”」'" and text.strip()[:1] not in "\"“「'":
                r = r[1:-1].strip()
            if r and core.Counter(UNITY_TOKEN_RE.findall(r)) == want:
                out = r
                break
        if out is None:
            self.failed += 1
            raise RuntimeError("translation failed")
        lead = text[: len(text) - len(text.lstrip())]
        trail = text[len(text.rstrip()):]
        out = lead + out + trail
        with self.lock:
            self.cache[text] = out
            self.meta[text] = cfg.get("model") or "?"
            self.dirty += 1
            self.count += 1
        return out


# ============================================================== 按模型删 Unity 译文

def _unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def _split_line(line):
    i = 0
    while i < len(line):
        if line[i] == "\\":
            i += 2
            continue
        if line[i] == "=":
            return line[:i], line[i + 1:]
        i += 1
    return None, None


def _game_entries(root):
    p = translation_file(root)
    try:
        with open(p, "r", encoding="utf-8-sig", errors="replace") as f:
            lines = f.read().splitlines()
    except OSError:
        return p, []
    return p, lines


def model_counts(root):
    meta = core.read_json(META_PATH, {}) or {}
    p, lines = _game_entries(root)
    c = core.Counter()
    for line in lines:
        if line.startswith("//"):
            continue
        k, v = _split_line(line)
        if k is None:
            continue
        c[meta.get(_unescape(k), core.UNKNOWN_MODEL)] += 1
    return c


