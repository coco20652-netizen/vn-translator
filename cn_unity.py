# ============================================================== 识别 Unity 游戏

def data_dir(root):
    try:
        names = sorted(os.listdir(root))
    except OSError:
        return None
    for d in names:
        if d.endswith("_Data") and os.path.isdir(os.path.join(root, d)) and os.path.isfile(os.path.join(root, d[:-5] + ".exe")):
            return d
    return None


def is_unity_root(root):
    d = data_dir(root)
    if not d:
        return False
    dp = os.path.join(root, d)
    return (os.path.isfile(os.path.join(root, "UnityPlayer.dll"))
            or any(os.path.exists(os.path.join(dp, x)) for x in ("globalgamemanagers", "mainData", "data.unity3d", "Managed", "il2cpp_data")))


def pe_arch(path):
    try:
        with open(path, "rb") as f:
            f.seek(0x3C)
            off = struct.unpack("<I", f.read(4))[0]
            f.seek(off)
            if f.read(4) != b"PE\0\0":
                return "x64"
            machine = struct.unpack("<H", f.read(2))[0]
        return "x86" if machine == 0x14C else "x64"
    except Exception:
        return "x64"


def unity_version(root, d):
    dp = os.path.join(root, d)
    for fn in ("globalgamemanagers", "mainData", "data.unity3d"):
        p = os.path.join(dp, fn)
        if os.path.isfile(p):
            try:
                with open(p, "rb") as f:
                    head = f.read(4096)
                m = re.search(rb"((?:20\d\d|6000|[45]\.\d)\.\d+\.\d+[abfpx]\d+)", head)
                if m:
                    return m.group(1).decode("ascii")
            except Exception:
                pass
    return "?"


def unity_info(root):
    d = data_dir(root)
    if not d:
        return None
    name = d[:-5]
    exe = os.path.join(root, name + ".exe")
    backend = "IL2CPP" if os.path.isfile(os.path.join(root, "GameAssembly.dll")) else "Mono"
    arch_src = os.path.join(root, "UnityPlayer.dll") if os.path.isfile(os.path.join(root, "UnityPlayer.dll")) else exe
    return {"title": name, "exe": exe, "data": d, "backend": backend,
            "arch": pe_arch(arch_src), "version": unity_version(root, d)}


