def download(url, log, stop):
    os.makedirs(DOWNLOAD_DIR, exist_ok=True)
    fn = url.rsplit("/", 1)[1]
    p = os.path.join(DOWNLOAD_DIR, fn)
    if os.path.isfile(p) and os.path.getsize(p) > 0:
        return p
    log("  下载 %s ……" % fn)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    try:
        with urllib.request.urlopen(req, timeout=60, context=core.SSL_CTX) as r, open(p + ".part", "wb") as f:
            total = int(r.headers.get("Content-Length") or 0)
            got, last = 0, 0
            while True:
                if stop is not None and stop.is_set():
                    raise core.StopRequested()
                chunk = r.read(256 * 1024)
                if not chunk:
                    break
                f.write(chunk)
                got += len(chunk)
                if got - last >= 5 * 1024 * 1024:
                    last = got
                    log("    已下载 %.1f / %.1f MB" % (got / 1048576.0, total / 1048576.0))
    except core.StopRequested:
        raise
    except Exception as e:
        try:
            os.remove(p + ".part")
        except OSError:
            pass
        raise RuntimeError("从 GitHub 下载 %s 失败（%s）。GitHub 连不上的话，开一下代理再试。" % (fn, e))
    os.replace(p + ".part", p)
    return p


def _extract_new(zip_path, root, created):
    """解压到游戏目录，已经存在的文件一律不覆盖；记录新建了哪些文件"""
    root_abs = os.path.abspath(root)
    with zipfile.ZipFile(zip_path) as z:
        for info in z.infolist():
            name = info.filename.replace("\\", "/")
            if name.endswith("/"):
                continue
            if name.lower().endswith(".md") and "/" in name and name.split("/")[-2] == "plugins":
                continue  # 插件自带的说明文件，不需要
            target = os.path.abspath(os.path.join(root, name))
            if not target.startswith(root_abs + os.sep):
                continue
            if os.path.exists(target):
                continue
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with z.open(info) as src, open(target, "wb") as dst:
                shutil.copyfileobj(src, dst)
            created.append(os.path.relpath(target, root_abs).replace("\\", "/"))


def _write_ini(path, settings):
    """只改我们管的几个键，其他内容原样保留"""
    lines = []
    if os.path.isfile(path):
        with open(path, "r", encoding="utf-8-sig", errors="replace") as f:
            lines = f.read().splitlines()
    pending = {sec: dict(kv) for sec, kv in settings.items()}
    out, sec = [], None

    def flush(section):
        for k, v in pending.get(section, {}).items():
            out.append("%s=%s" % (k, v))
        pending[section] = {}

    for line in lines:
        m = re.match(r"\s*\[(.+?)\]\s*$", line)
        if m:
            if sec is not None:
                flush(sec)
            sec = m.group(1)
            out.append(line)
            continue
        m = re.match(r"\s*([^=;#\s][^=]*?)\s*=", line)
        if m and sec in pending and m.group(1) in pending[sec]:
            k = m.group(1)
            out.append("%s=%s" % (k, pending[sec].pop(k)))
            continue
        out.append(line)
    if sec is not None:
        flush(sec)
    for s, kv in pending.items():
        if kv:
            out.append("")
            out.append("[%s]" % s)
            for k, v in kv.items():
                out.append("%s=%s" % (k, v))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


